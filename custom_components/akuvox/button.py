"""Button platform for akuvox."""
from homeassistant.components.button import ButtonEntity
from homeassistant.helpers import storage
from homeassistant.helpers.entity import DeviceInfo

from .api import AkuvoxApiClient
from .coordinator import AkuvoxDataUpdateCoordinator
from .const import (
    DOMAIN,
    LOGGER,
    NAME,
    VERSION,
    DATA_STORAGE_KEY
)
from .entity import AkuvoxEntity

async def async_setup_entry(hass, entry, async_add_devices):
    """Set up the door relay platform."""
    coordinator: AkuvoxDataUpdateCoordinator
    for _key, value in hass.data[DOMAIN].items():
        coordinator = value
    client = coordinator.client

    store = storage.Store(hass, 1, DATA_STORAGE_KEY)
    device_data: dict = await store.async_load() # type: ignore
    door_relay_data = device_data["door_relay_data"]

    entities = []
    for door_relay in door_relay_data:
        name = door_relay["name"]
        mac = door_relay["mac"]
        relay_id = door_relay["relay_id"]
        data = f"mac={mac}&relay={relay_id}"

        entities.append(
            AkuvoxDoorRelayEntity(
                client=client,
                entry=entry,
                name=name,
                relay_id=relay_id,
                data=data,
            )
        )

    entities.append(AkuvoxExportSipConfigButton(client=client, entry=entry))
    async_add_devices(entities)


class AkuvoxDoorRelayEntity(ButtonEntity, AkuvoxEntity):
    """Akuvox door relay class."""

    _client: AkuvoxApiClient
    _name: str = ""
    _host: str = ""
    _token: str = ""
    _data: str = ""

    def __init__(
        self,
        client: AkuvoxApiClient,
        entry,
        name: str,
        relay_id: str,
        data: str,
    ) -> None:
        """Initialize the Akuvox door relay class."""
        super(ButtonEntity, self).__init__(client=client, entry=entry)
        AkuvoxEntity.__init__(
            self=self,
            client=client,
            entry=entry
        )
        unique_name = name + ", " + relay_id
        self._client = client
        self._name = unique_name
        self._host = self.get_saved_value("host")
        self._token = self.get_saved_value("token")
        self._data = data

        self._attr_unique_id = unique_name
        self._attr_name = unique_name

        LOGGER.debug("Adding Akuvox door relay '%s'", unique_name)
        self._attr_device_info = DeviceInfo(
            identifiers={(DOMAIN, name)},  # type: ignore
            name=name,
            model=VERSION,
            manufacturer=NAME,
        )

    def press(self) -> None:
        """Trigger the door relay."""
        self._client.make_opendoor_request(
            name=self._name,
            host=self._host,
            token=self._token,
            data=self._data
        )



SIP_EXPORT_PATH = "akuvox_ha_sip.yaml"
_TRANSPORT_NAMES = {"0": "udp", "1": "tcp", "2": "tls"}


def _build_ha_sip_config(sip_conf: dict, webhook_id: str) -> tuple[str, str]:
    """Build an ha-sip add-on configuration from the SmartPlus SIP account.

    Returns (yaml_text, summary). The summary contains no secrets.
    """
    server = str(sip_conf.get("sip_server") or "").strip()
    host = server.split(":")[0]
    transport = _TRANSPORT_NAMES.get(str(sip_conf.get("trans_type")), "udp")
    uri_suffix = "" if transport == "udp" else f";transport={transport}"
    tls = "enabled" if transport == "tls" else "disabled"

    def account(user, password, enabled):
        user = str(user or "")
        password = str(password or "")
        return (
            f"  enabled: {'true' if enabled else 'false'}\n"
            f"  registrar_uri: 'sip:{server}{uri_suffix}'\n"
            f"  id_uri: 'sip:{user}@{host}'\n"
            f"  realm: '*'\n"
            f"  user_name: \"{user}\"\n"
            f"  password: \"{password}\"\n"
            f"  answer_mode: listen\n"
            f"  settle_time: 1\n"
            f"  incoming_call_file: ''\n"
            f"  options: '--use-contact-rewrite enabled --use-via-rewrite enabled --use-sdp-nat-rewrite enabled'\n"
        )

    same = (str(sip_conf.get("sip")) == str(sip_conf.get("main_sip"))
            and str(sip_conf.get("sip_passwd")) == str(sip_conf.get("main_sip_passwd")))
    text = (
        "# ha-sip add-on configuration generated by the Akuvox integration.\n"
        "# Contains your SmartPlus SIP password - keep this file private and\n"
        "# delete it once you have copied the settings into the add-on.\n"
        "#\n"
        "# sip   = the SmartPlus app's own SIP account (test this first)\n"
        "# sip_2 = the apartment's main SIP account (disabled; try it if the\n"
        "#         iPhone stops ringing while ha-sip uses 'sip')\n"
        f"# main account identical to app account: {'yes' if same else 'no'}\n"
        "sip_global:\n"
        "  port: 5060\n"
        "  log_level: 5\n"
        "  name_server: ''\n"
        "  cache_dir: ''\n"
        f"  global_options: '--udp enabled --tcp enabled --tls {tls}'\n"
        "sip:\n" + account(sip_conf.get("sip"), sip_conf.get("sip_passwd"), True)
        + "sip_2:\n" + account(sip_conf.get("main_sip"), sip_conf.get("main_sip_passwd"), False)
        + "sip_3:\n"
        "  enabled: false\n"
        "  registrar_uri: 'sip:127.0.0.1'\n"
        "  id_uri: ''\n"
        "  realm: '*'\n"
        "  user_name: ''\n"
        "  password: ''\n"
        "  answer_mode: listen\n"
        "  settle_time: 1\n"
        "  incoming_call_file: ''\n"
        "  options: ''\n"
        "tts:\n"
        "  engine_id: ''\n"
        "  platform: ''\n"
        "  language: da\n"
        "  voice: ''\n"
        "  debug_print: false\n"
        + "webhook:\n"
        f"  id: {webhook_id}\n"
        "sensors:\n"
        "  enabled: true\n"
        "  entity_prefix: akuvox_sip\n"
    )
    summary = (f"server host length {len(host)}, transport {transport}, "
               f"codec {sip_conf.get('codec')}, main account identical: {same}")
    return text, summary


class AkuvoxExportSipConfigButton(ButtonEntity):
    """Writes an ha-sip configuration for the SmartPlus SIP account to /config."""

    _attr_has_entity_name = False
    _attr_icon = "mdi:phone-settings"

    def __init__(self, client: AkuvoxApiClient, entry) -> None:
        """Initialize the export button."""
        self._client = client
        self._attr_name = "Akuvox export SIP config"
        self._attr_unique_id = f"{entry.entry_id}_export_sip_config"
        from homeassistant.helpers.entity import EntityCategory
        self._attr_entity_category = EntityCategory.CONFIG

    async def async_press(self) -> None:
        """Write the ha-sip config file."""
        data = getattr(self._client, "_data", None)
        sip_conf = getattr(data, "sip_conf", None) if data else None
        if not sip_conf or not sip_conf.get("sip") or not sip_conf.get("sip_server"):
            LOGGER.error("No SmartPlus SIP account available yet; reload the integration and try again")
            return
        import secrets
        webhook_id = f"akuvox_door_call_{secrets.token_hex(8)}"
        text, summary = _build_ha_sip_config(sip_conf, webhook_id)
        path = self.hass.config.path(SIP_EXPORT_PATH)

        def _write():
            import os
            with open(path, "w", encoding="utf-8") as file:
                file.write(text)
            os.chmod(path, 0o600)

        await self.hass.async_add_executor_job(_write)
        LOGGER.warning("📄 ha-sip configuration written to %s (%s); webhook id: %s",
                       path, summary, webhook_id)
